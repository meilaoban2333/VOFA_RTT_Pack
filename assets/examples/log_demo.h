/*
***********************************************************************
* 文件名：log_demo.h
* 说  明：RTT 下行命令 + 按需打印的示例模板（可选，不依赖它也能用波形输出）
*
* 用途：把要观察的变量分组编号，运行时用 VOFA+ / RTT Viewer 发命令动态开关，
*       不用改代码重新烧录就能切换看哪几组波形。
*
* 命令格式：AT+XX,YY
      XX/YY 为项目号，可只发一个，也可发多个
*   AT+1
      -> 切换 1 号
*   AT+1,2
    -> 同时切换 1 号和 2 号，两项都开则一起打印
*   再发一次同样的号即关闭该项（每个号独立翻转）
*   AT+0
      -> 全部关闭
*
* 输出为 VOFA+ FireWater 纯数据格式，无标签，通道按项目号从小到大排列。
* 如同时开 1、2 号（示例里是角度 + 三相电流）：
*   1.571,0.050,-0.020,-0.030
*
* 移植：把下面的 LOG_ID_xxx 和 log_demo.c 里 LogPrint() 的取值代码
*       换成自己工程的变量，其余逻辑不用动。
***********************************************************************
*/

#ifndef __LOG_DEMO_H__
#define __LOG_DEMO_H__

#include <stdint.h>   /* uint8_t / uint32_t，不依赖 HAL 的 main.h */

/* 日志项目号：发 AT+<号> 翻转对应项。按自己的工程改这张表 */
#define LOG_ID_OFF   0 // 全部关闭，固定含义，不要占用
#define LOG_ID_ANGLE 1 // 示例：电角度，rad
#define LOG_ID_CUR   2 // 示例：三相电流，A
#define LOG_ID_VBUS  3 // 示例：母线电压，V
#define LOG_ID_SPEED 4 // 示例：转速，rpm

/* 全开时的通道总数：角度1 + 电流3 + 母线1 + 转速2。
   必须 <= vofa_rtt.h 里的 VOFA_CH_MAX，否则整帧会被丢弃 */
#define LOG_CH_MAX   7

/* 周期调用：解析下行命令 + 打印已开启项。建议 20~50ms 一次 */
void LogTask(void);

#endif
